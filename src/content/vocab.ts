import { CORE_WORDS } from './core'
import type { CEFR, Word } from './types'

type Seed = Omit<Word, 'level' | 'tags'> & { level?: CEFR; tags?: string[] }

function pack(level: CEFR, tag: string, seeds: Seed[]): Word[] {
  return seeds.map((s) => ({ ...s, level: s.level ?? level, tags: [tag, ...(s.tags ?? [])] }))
}

