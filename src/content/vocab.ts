/**
 * Compare two entries as the same lexical item: "l'ami / l'amie" and
 * "un ami / une amie" are one word, not two dictionary rows.
 *
 * The part of speech is part of the key on purpose: `le français` (the
 * language) and `français / française` (the adjective) are different entries
 * that happen to share a head form.
 */
function lexicalKey(w: Pick<Word, 'fr' | 'pos'>) {
  const ARTICLES = new Set(['le', 'la', 'les', "l'", 'un', 'une', 'des', 'du'])
  const parts = w.fr
    .toLowerCase()
    .replace(/[’]/g, "'")
    .split('/')
    .map((p) => p.trim())
    .filter(Boolean)

  // "le / la journaliste" — skip the bare article and key on the noun itself.
  for (const part of parts) {
    if (ARTICLES.has(part)) continue
    const head = part.replace(/^(le |la |les |l'|un |une |des |du |de la |de l')/, '').trim()
    if (head) return `${head}|${w.pos ?? ''}`
  }

  // Entries that are nothing but articles ("un / une / des") key on themselves.
  return `${w.fr.toLowerCase()}|${w.pos ?? ''}`
}

/**
 * Merge the frequency core into the thematic list.
 *
 * A course word that also appears in the top 1000 keeps its richer authored
 * entry (example sentence, lesson tag) and simply gains a `rank`; only genuinely
 * new words are appended. That way the two lists can be maintained independently
 * without ever producing duplicate dictionary rows.
 */
function mergeVocabulary(): Word[] {
  const merged: Word[] = []
  const seenId = new Map<string, Word>()
  const seenKey = new Map<string, Word>()

  const remember = (w: Word) => {
    merged.push(w)
    seenId.set(w.id, w)
    seenKey.set(lexicalKey(w), w)
  }

  for (const w of thematic) remember(w)

  for (const core of CORE_WORDS) {
    const existing = seenId.get(core.id) ?? seenKey.get(lexicalKey(core))
    if (existing) {
      // The thematic entry wins on content, but inherits the frequency rank.
      existing.rank ??= core.rank
      if (!existing.tags?.includes('core')) existing.tags = [...(existing.tags ?? []), 'core']
      continue
    }
    remember(core)
  }

  return merged
}

export const WORDS: Word[] = mergeVocabulary()

const byId = new Map(WORDS.map((w) => [w.id, w]))

export function getWord(id: string): Word | undefined {
  return byId.get(id)
}

export function getWords(ids: readonly string[]): Word[] {
  return ids.map((id) => byId.get(id)).filter((w): w is Word => Boolean(w))
}

export function wordsByTag(tag: string): Word[] {
  return WORDS.filter((w) => w.tags?.includes(tag))
}
